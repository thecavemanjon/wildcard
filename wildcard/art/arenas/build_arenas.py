def theme_pals(ramp):
    if ramp is None:
        import copy
        p = copy.deepcopy(S.kit.pals)
        for ci in range(11, 16): p[8][ci] = S.ramp_map(p[8][ci], S.STONE)
        return p
    return S.pals(ramp)

def write_jasc(path, colours):
    with open(path, 'w') as f:
        f.write('JASC-PAL\r\n0100\r\n16\r\n' + ''.join(f'{r} {g} {b}\r\n' for r, g, b in colours))

def write_tileset(theme):
    d = R + f'data/tilesets/secondary/wildcard_{theme.lower()}/palettes/'
    os.makedirs(d, exist_ok=True)
    src = R + 'data/tilesets/secondary/lavaridge/palettes/'
    pals = theme_pals(RAMPS[theme])
    for i in range(16):
        if 6 <= i <= 12:
            write_jasc(d + f'{i:02}.pal', pals[i])
        else:   # palettes the secondary set doesn't own: copied as they are
            open(d + f'{i:02}.pal', 'w').write(open(src + f'{i:02}.pal').read())

def tileset_c_blocks():
    gfx, head = [MARK_BEGIN], [MARK_BEGIN]
    for theme in RAMPS:
        n = theme.lower()
        gfx.append(f'const u16 gTilesetPalettes_Wildcard{theme}[][16] =\n{{')
        gfx += [f'    INCGFX_U16("data/tilesets/secondary/wildcard_{n}/palettes/{i:02}.pal", ".gbapal"),' for i in range(16)]
        gfx.append('};\n')
        head.append(f'const struct Tileset gTileset_Wildcard{theme} =\n{{\n    .isCompressed = TRUE,\n    .isSecondary = TRUE,\n'
                    f'    .tiles = gTilesetTiles_Lavaridge, // Mt. Chimney\'s tiles, recoloured\n'
                    f'    .palettes = gTilesetPalettes_Wildcard{theme},\n    .metatiles = gMetatiles_Lavaridge,\n'
                    f'    .metatileAttributes = gMetatileAttributes_Lavaridge,\n    .callback = InitTilesetAnim_Lavaridge,\n}};\n')
    gfx.append(MARK_END); head.append(MARK_END)
    return '\n'.join(gfx) + '\n', '\n'.join(head) + '\n'

def splice(path, block, before='#else'):
    """Puts block just before the Emerald section's #else (or replaces the marked block)."""
    s = open(path).read()
    if MARK_BEGIN in s:
        a = s.index(MARK_BEGIN); b = s.index(MARK_END) + len(MARK_END) + 1
        s = s[:a] + block + s[b:]
    else:
        i = s.index('\n' + before + '\n') + 1
        s = s[:i] + block + '\n' + s[i:]
    open(path, 'w').write(s)

# ---- collision ------------------------------------------------------------------
def chimney_collision():
    """Each Lavaridge metatile's usual (collision, elevation), learnt from Mt. Chimney."""
    lid, _ = mk.map_layout('MtChimney'); _, g = mk.layout(lid)
    seen = {}
    for row in g:
        for v in row: seen.setdefault(v & 0x3FF, Counter())[(v >> 10) & 3, v >> 12] += 1
    return {m: c.most_common(1)[0][0] for m, c in seen.items()}

COLL = chimney_collision()
WALKABLE = {S.G, S.STEP, A.LAVA}   # lava is walled off below

def with_collision(g, start, extra_blocked=()):
    """Metatile ids -> block values. Everything the player can't reach from the
    start is solid, so nobody wanders onto the scenery."""
    H, W = len(g), len(g[0])
    passable = lambda x, y: (g[y][x] & 0x3FF) in (S.G, S.STEP) and (x, y) not in extra_blocked
    reach, q = set(), deque([start])
    while q:
        x, y = q.popleft()
        if (x, y) in reach or not (0 <= x < W and 0 <= y < H) or not passable(x, y): continue
        reach.add((x, y)); q.extend([(x+1, y), (x-1, y), (x, y+1), (x, y-1)])
    out = []
    for y in range(H):
        row = []
        for x in range(W):
            m = g[y][x] & 0x3FF
            if (x, y) in reach: coll, elev = 0, 3
            else: coll, elev = 1, COLL.get(m, (1, 0))[1] or 3
            row.append(m | coll << 10 | elev << 12)
        out.append(row)
    return out, reach

# ---- map files --------------------------------------------------------------------
def write_layout(name, rows, border):
    d = R + f'data/layouts/{name}/'
    os.makedirs(d, exist_ok=True)
    open(d + 'map.bin', 'wb').write(b''.join(struct.pack('<H', v) for r in rows for v in r))
    open(d + 'border.bin', 'wb').write(b''.join(struct.pack('<H', v) for v in border))

def obj(gfx, x, y, script='UnderdogArena_EventScript_Opponent', move='MOVEMENT_TYPE_FACE_DOWN'):
    return {'graphics_id': gfx, 'x': x, 'y': y, 'elevation': 3, 'movement_type': move,
            'movement_range_x': 0, 'movement_range_y': 0, 'trainer_type': 'TRAINER_TYPE_NONE',
            'trainer_sight_or_berry_tree_id': '0', 'script': script, 'flag': '0'}

def write_map(name, layout_id, music, weather, objs, map_type='MAP_TYPE_INDOOR', note='', face='DIR_NORTH'):
    d = R + f'data/maps/{name}/'
    os.makedirs(d, exist_ok=True)
    mid = 'MAP_' + ''.join('_' + c if c.isupper() and i and not name[i-1] == '_' else c for i, c in enumerate(name)).upper().replace('__', '_')
    m = {'id': mid, 'name': name, 'layout': layout_id, 'music': music, 'region': 'REGION_HOENN',
         'region_map_section': 'MAPSEC_BATTLE_FRONTIER', 'requires_flash': False, 'weather': weather,
         'map_type': map_type, 'allow_cycling': False, 'allow_escaping': False, 'allow_running': True,
         'show_map_name': False, 'battle_scene': 'MAP_BATTLE_SCENE_NORMAL', 'connections': None,
         'object_events': objs, 'warp_events': [], 'coord_events': [], 'bg_events': []}
    json.dump(m, open(d + 'map.json', 'w'), indent=2); open(d + 'map.json', 'a').write('\n')
    open(d + 'scripts.inc', 'w').write(
        f'@ Daily Underdog arena (generated by wildcard/art/arenas/build_arenas.py): {note}\n'
        f'@ The battle is the shared UnderdogArena_EventScript_Opponent.\n'
        f'{name}_MapScripts::\n\tmap_script MAP_SCRIPT_ON_WARP_INTO_MAP_TABLE, {name}_OnWarp\n\t.byte 0\n\n'
        f'{name}_OnWarp:\n\tmap_script_2 VAR_TEMP_1, 0, {name}_EventScript_PlayerTurn\n\t.2byte 0\n\n'
        f'{name}_EventScript_PlayerTurn::\n\tturnobject LOCALID_PLAYER, {face}\n\tsetvar VAR_TEMP_1, 1\n\tend\n')
    return mid

LAYOUTS, MAPS, ROOMS = [], [], {}

def add_layout(name, W, H, secondary, primary='gTileset_General'):
    lid = 'LAYOUT_' + ''.join('_' + c if c.isupper() and i and name[i-1] != '_' else c for i, c in enumerate(name)).upper().replace('__', '_')
    LAYOUTS.append({'id': lid, 'name': name + '_Layout', 'width': W, 'height': H, 'primary_tileset': primary,
                    'secondary_tileset': secondary, 'border_filepath': f'data/layouts/{name}/border.bin',
                    'blockdata_filepath': f'data/layouts/{name}/map.bin', 'layout_version': 'emerald'})
    return lid

# ---- the arenas --------------------------------------------------------------------
ROCK_BORDER = [S.H | 1 << 10] * 4

def summit_red():
    g, cx, ry, _ = S.gsc()
    start = (cx, 9)
    rows, reach = with_collision(g, start)
    assert (cx, ry + 1) in reach, 'Red must be reachable'
    write_layout('UnderdogArena_Summit', rows, ROCK_BORDER)
    lid = add_layout('UnderdogArena_Summit', len(g[0]), len(g), 'gTileset_WildcardSnow')
    return lid, (cx, ry), start

def amphitheatre(theme, decor):
    g, cx, sprites = A.build(decor)
    start = (cx, 10)
    boulders = {(x, y) for _, x, y in sprites}
    rows, reach = with_collision(g, start, boulders)
    assert (cx, 7) in reach
    name = f'UnderdogArena_Amph{theme}'
    write_layout(name, rows, ROCK_BORDER)
    lid = add_layout(name, len(g[0]), len(g), f'gTileset_Wildcard{theme}')
    return name, lid, (cx, 6), start, sorted(boulders)

