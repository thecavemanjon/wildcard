# Builds the new arenas into the game's data (not the ROM): layouts, recoloured
# tilesets, map JSON and map scripts, plus the layouts.json / map_groups.json
# entries and the tileset C blocks. Rerunnable: everything it writes is either
# its own file or a marked block it replaces.
#
#   cd wildcard/art/arenas && python3 build_arenas.py
#
# The designs are the picked mockups (DECISIONS 2026-10-15/16): the
# Gold/Silver/Crystal keyhole summit for Red (summit.gsc), the type
# amphitheatres for the Kanto opponents (amph.build), the Battle Dome stadium
# for Blue (stadium.grand), and the Battle Arena dojo / Battle Palace pool rooms.
import json, os, struct
from collections import Counter, deque
import mapkit as mk, summit as S, amph as A, stadium as ST

R = mk.R
MARK_BEGIN = '// Daily Underdog: arena tilesets (generated by wildcard/art/arenas/build_arenas.py; edit there)'
MARK_END = '// Daily Underdog: end of arena tilesets'

