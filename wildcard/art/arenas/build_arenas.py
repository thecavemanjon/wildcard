def main():
    for theme in RAMPS: write_tileset(theme)
    gfx, head = tileset_c_blocks()
    splice(R + 'src/data/tilesets/graphics.h', gfx)
    splice(R + 'src/data/tilesets/headers.h', head)

    # Red: the keyhole summit replaces Mt. Pyre's summit in his existing arena map.
    lid, (rx, ry), start = summit_red()
    red = json.load(open(R + 'data/maps/UnderdogArena_Red/map.json'))
    red['layout'] = lid
    red['object_events'][0].update({'x': rx, 'y': ry})
    json.dump(red, open(R + 'data/maps/UnderdogArena_Red/map.json', 'w'), indent=2); open(R + 'data/maps/UnderdogArena_Red/map.json', 'a').write('\n')
    ROOMS[34] = ROOMS[38] = ('MAP_UNDERDOG_ARENA_RED', start, 'Red, on the summit')

    for slot, who, theme, decor in KANTO:
        name, lid, (ox, oy), start, boulders = amphitheatre(theme, decor)
        objs = [obj('OBJ_EVENT_GFX_VAR_0', ox, oy)] + [obj('OBJ_EVENT_GFX_PUSHABLE_BOULDER', x, y, '0x0') for x, y in boulders]
        weather = 'WEATHER_SNOW' if theme == 'Ice' else 'WEATHER_NONE'
        mid = write_map(name, lid, 'MUS_GYM', weather, objs, 'MAP_TYPE_ROUTE', f'the {theme.lower()} amphitheatre ({who}).')
        MAPS.append(name); ROOMS[slot] = (mid, start, f'{who}: {theme.lower()} amphitheatre')

    # Bruno and Misty: the Battle Arena's tatami dojo and the Battle Palace's pool room.
    mid = write_map('UnderdogArena_Dojo', 'LAYOUT_BATTLE_FRONTIER_BATTLE_ARENA_BATTLE_ROOM', 'MUS_B_ARENA', 'WEATHER_NONE',
                    [obj('OBJ_EVENT_GFX_VAR_0', 7, 4)], note='the Battle Arena dojo (Bruno).')
    MAPS.append('UnderdogArena_Dojo'); ROOMS[31] = (mid, (7, 7), 'Bruno: dojo')
    # The Battle Palace's carpet is solid (nobody walks on it there): our copy makes it floor.
    lid, _ = mk.map_layout('BattleFrontier_BattlePalaceBattleRoom'); _, pal = mk.layout(lid)
    for y in range(3, 9):
        for x in range(4, 11): pal[y][x] = (pal[y][x] & 0x3FF) | 3 << 12
    write_layout('UnderdogArena_WaterPalace', pal, list(struct.unpack('<4H', open(R + 'data/layouts/BattleFrontier_BattlePalaceBattleRoom/border.bin', 'rb').read())))
    lid = add_layout('UnderdogArena_WaterPalace', len(pal[0]), len(pal), 'gTileset_BattlePalace')
    mid = write_map('UnderdogArena_WaterPalace', lid, 'MUS_B_PALACE', 'WEATHER_NONE',
                    [obj('OBJ_EVENT_GFX_VAR_0', 7, 3)], note='the Battle Palace pool (Misty).')
    MAPS.append('UnderdogArena_WaterPalace'); ROOMS[23] = (mid, (7, 7), 'Misty: water palace')

    # Blue: the Battle Dome stadium, him on the centre spot, you walking over from the left podium.
    g = ST.grand()
    write_layout('UnderdogArena_Stadium', g, [ST.FLOOR]*4)
    lid = add_layout('UnderdogArena_Stadium', len(g[0]), len(g), 'gTileset_BattleDome', 'gTileset_Building')
    mid = write_map('UnderdogArena_Stadium', lid, 'MUS_B_DOME', 'WEATHER_NONE',
                    [obj('OBJ_EVENT_GFX_VAR_0', 12, 7, move='MOVEMENT_TYPE_FACE_LEFT')], note='the stadium (Blue waits on the centre spot; you start on the left podium).', face='DIR_EAST')
    MAPS.append('UnderdogArena_Stadium')
    for slot in (35, 36, 37): ROOMS[slot] = (mid, (7, 7), 'Blue: stadium')

    # layouts.json and map_groups.json (replacing earlier runs' entries)
    p = R + 'data/layouts/layouts.json'; L = json.load(open(p))
    ids = {l['id'] for l in LAYOUTS}
    L['layouts'] = [l for l in L['layouts'] if l.get('id') not in ids] + LAYOUTS
    json.dump(L, open(p, 'w'), indent=2); open(p, 'a').write('\n')
    p = R + 'data/maps/map_groups.json'; M = json.load(open(p))
    grp = M['gMapGroup_UnderdogArenas']
    for n in MAPS:
        if n not in grp: grp.append(n)
    json.dump(M, open(p, 'w'), indent=2); open(p, 'a').write('\n')

    # each map's script file is listed by hand in data/event_scripts.s
    p = R + 'data/event_scripts.s'; ev = open(p).read()
    anchor = '\t.include "data/maps/UnderdogArena_Red/scripts.inc"\n'
    add = ''.join(f'\t.include "data/maps/{n}/scripts.inc"\n' for n in MAPS if f'data/maps/{n}/scripts.inc' not in ev)
    open(p, 'w').write(ev.replace(anchor, anchor + add))

    print('sArenaRooms changes (src/daily_underdog.c):')
    for slot in sorted(ROOMS):
        mid, (x, y), who = ROOMS[slot]
        print(f'    [{slot:2}] = {{ {mid + ",":38} {x:2}, {y:2} }}, // {who}')

if __name__ == '__main__':
    main()
