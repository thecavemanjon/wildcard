# Builds the bedroom's own tileset (a copy of Brendan's house) with the room
# themes' extras (DECISIONS 2026-10-20): the stairwell shifted a tile right, a
# window on the freed wall tile whose view follows the theme and the clock, and
# potted plants a theme can put down. Rerunnable: rewrites its own files and
# the marked blocks it owns.
#
#   cd wildcard/art/rooms && python3 build_bedroom.py
#
# Writes data/tilesets/secondary/wildcard_bedroom/ (tiles, palettes, metatiles,
# anim/window.png), the bedroom layout's map.bin, layouts.json's tileset entry,
# include/constants/wildcard_bedroom.h, src/data/tilesets/wildcard_bedroom_anims.h
# and marked blocks in src/data/tilesets/{graphics,metatiles,headers}.h and
# include/tileset_anims.h. The C side: TilesetAnim_WildcardBedroom in
# src/tileset_anims.c, themes in src/daily_underdog.c (sRoomThemes).
import os, sys, json, struct, shutil
from PIL import Image
import og_rooms as O
from roomkit import mk, rect, put

R = mk.R
SRC = R + 'data/tilesets/secondary/brendans_mays_house/'
DST = R + 'data/tilesets/secondary/wildcard_bedroom/'
LAYOUT_DIR = R + 'data/layouts/UnderdogBedroom/'
MARK_BEGIN = '// Daily Underdog: bedroom tileset (generated by wildcard/art/rooms/build_bedroom.py; edit there)'
MARK_END = '// Daily Underdog: end of bedroom tileset'
SEC = 512                 # secondary tiles and metatiles start here (Emerald)
WIN_PAL = 12              # the one secondary palette Brendan's house leaves free
KEY = (255, 0, 255)

# Views, in the order of the WINDOW_VIEW_* constants. 'poster' is the Cosy Attic's Pikachu.
VIEWS = ['sky', 'poster', 'sea', 'snow', 'leaves', 'city', 'stars', 'blossom', 'fish', 'lava']
TIMES = ['day', 'sunset', 'night']   # TIME_MORNING and TIME_DAY show 'day'
FRAMES = 4
FRAME_T = (0, 8, 16, 24)             # mockup time for each animation frame

# Palette 12: 1-7 change with the view; 8-15 are the plant's, fixed (the window
# borrows its white and outline).
PLANT_SLOTS = 8

def jasc_read(p):
    return [tuple(int(v) for v in l.split()) for l in open(p).read().split('\n')[3:19]]

def jasc_write(p, cols):
    cols = (list(cols) + [(0, 0, 0)] * 16)[:16]
    open(p, 'w').write('JASC-PAL\r\n0100\r\n16\r\n' + ''.join(f'{r} {g} {b}\r\n' for r, g, b in cols))

def gba(c): return tuple((v >> 3) << 3 for v in c[:3])

def rgb555(c): return (c[0] >> 3) | ((c[1] >> 3) << 5) | ((c[2] >> 3) << 10)

# ---- art ---------------------------------------------------------------------------------------
def plant_art():
    """16 x 32, the pot sitting on the bottom edge; floor bits in Rustboro's art dropped."""
    src = O.house_top().crop((0, 112, 16, 144))
    floor = {(213, 197, 74), (172, 139, 57), (148, 115, 41)}
    out = Image.new('RGB', (16, 32), KEY); o = out.load(); px = src.load()
    for y in range(32):
        for x in range(16):
            c = px[x, y]
            if c[3] and c[:3] not in floor: o[x, y] = gba(c)
    return out

def window_art(view, time, t):
    """16 x 32 (the wall tile at column 6): the window with its sill, KEY elsewhere."""
    img = Image.new('RGB', (16, 32), KEY)
    if view == 'poster':
        O.poster(img, 1, 4, 'pikachu')
    else:
        O.window(img, time, t, x=2, y=4, w=13, h=18, view=O.VIEWS.get(view))
    px = img.load()
    for y in range(32):
        for x in range(16):
            if px[x, y] != KEY: px[x, y] = gba(px[x, y])
    return img

def quantise(colours, n, fixed):
    """Merge the least-used colours into their nearest neighbours until n remain
    (plus the fixed ones, which absorb anything close). Returns {colour: target}."""
    counts = dict(colours)
    keep = sorted(counts, key=lambda c: -counts[c])
    mapping = {c: c for c in counts}
    def d(a, b): return sum((a[i] - b[i]) ** 2 for i in range(3))
    for c in list(keep):
        for f in fixed:
            if d(c, f) < 120: mapping[c] = f
    free = [c for c in keep if mapping[c] == c and c not in fixed]
    while len(free) > n:
        c = free.pop()   # least used
        target = min(free + list(fixed), key=lambda o: d(o, c))
        for k, v in mapping.items():
            if v == c: mapping[k] = target
    return mapping, free

# ---- tileset maths -------------------------------------------------------------------------------
def load_metatiles(d):
    b = open(d + 'metatiles.bin', 'rb').read()
    return [list(struct.unpack_from('<8H', b, i * 16)) for i in range(len(b) // 16)]

def load_attrs(d):
    a = open(d + 'metatile_attributes.bin', 'rb').read()
    return [struct.unpack_from('<H', a, i * 2)[0] for i in range(len(a) // 2)]

def tiles_of(img):
    w, h = img.size; px = img.load()
    return [[[px[tx * 8 + x, ty * 8 + y] for x in range(8)] for y in range(8)] for ty in range(h // 8) for tx in range(w // 8)]

def to_png(tiles, path, palette_cols, per_row=16):
    rows = (len(tiles) + per_row - 1) // per_row
    im = Image.new('P', (per_row * 8, rows * 8), 0)
    flat = []
    for c in (list(palette_cols) + [(0, 0, 0)] * 16)[:16]: flat += list(c)
    im.putpalette(flat + [0] * (768 - len(flat)))
    px = im.load()
    for i, t in enumerate(tiles):
        tx, ty = (i % per_row) * 8, (i // per_row) * 8
        for y in range(8):
            for x in range(8): px[tx + x, ty + y] = t[y][x]
    im.save(path)

def image_tiles(img, index_of):
    """8x8 tiles of img (row-major) as palette indices."""
    px = img.load(); out = []
    for ty in range(img.height // 8):
        for tx in range(img.width // 8):
            out.append([[index_of(px[tx * 8 + x, ty * 8 + y]) for x in range(8)] for y in range(8)])
    return out

def entry(tile, pal, h=0, v=0): return tile | (h << 10) | (v << 11) | (pal << 12)

# ---- marked blocks -----------------------------------------------------------------------------
def write_block(path, text):
    s = open(path).read()
    block = MARK_BEGIN + '\n' + text.rstrip() + '\n' + MARK_END + '\n'
    if MARK_BEGIN in s:
        a = s.index(MARK_BEGIN); b = s.index(MARK_END) + len(MARK_END) + 1
        s = s[:a] + block + s[b:]
    else:
        s = s.rstrip('\n') + '\n\n' + block
    open(path, 'w').write(s)

# ---- build -----------------------------------------------------------------------------------
def main():
    os.makedirs(DST + 'palettes', exist_ok=True); os.makedirs(DST + 'anim', exist_ok=True)
    src_png = Image.open(SRC + 'tiles.png')
    tiles = tiles_of(src_png)
    mets = load_metatiles(SRC); attrs = load_attrs(SRC)
    pals = [jasc_read(SRC + f'palettes/{i:02}.pal') for i in range(16)]
    lay = json.load(open(R + 'data/layouts/layouts.json'))
    L = next(l for l in lay['layouts'] if l.get('id') == 'LAYOUT_UNDERDOG_BEDROOM')
    W = L['width']
    grid = list(struct.unpack(f'<{L["width"] * L["height"]}H', open(R + L['blockdata_filepath'], 'rb').read()))
    def cell(x, y): return grid[y * W + x]
    PRI = R + 'data/tilesets/primary/building/'
    pmets, pattrs = load_metatiles(PRI), load_attrs(PRI)
    def met(mid): return list(mets[mid - SEC] if mid >= SEC else pmets[mid])
    def attr(mid): return attrs[mid - SEC] if mid >= SEC else pattrs[mid]

    # Palette 12: plant colours fixed in 8-15, the window's first view in 1-7.
    plant = plant_art()
    pcols = sorted({c for c in plant.getdata() if c != KEY}, key=lambda c: sum(c))
    assert len(pcols) <= PLANT_SLOTS, pcols
    fixed = (pcols + [(0, 0, 0)] * PLANT_SLOTS)[:PLANT_SLOTS]
    white = max(pcols, key=sum); outline = min(pcols, key=sum)

    # Every view/time: frames and their palette.
    frames, view_pals = [], []
    for v in VIEWS:
        for tm in TIMES:
            arts = [window_art(v, tm, t) for t in FRAME_T]
            counts = {}
            for a in arts:
                for c in a.getdata():
                    if c != KEY: counts[c] = counts.get(c, 0) + 1
            # the frame's white and outline become the plant's
            mapping, free = quantise(counts, 7, (white, outline))
            pal = [(0, 0, 0)] + (free + [(0, 0, 0)] * 7)[:7] + fixed
            def idx(c, mapping=mapping, pal=pal):
                if c == KEY: return 0
                return pal.index(mapping[c], 1)
            for a in arts: frames.append(image_tiles(a, idx))
            view_pals.append([rgb555(c) for c in pal])

    # New tiles: the window (its first frame) then the plant, 8 each.
    base_tile = len(tiles)
    win_tiles = frames[0]
    plant_tiles = image_tiles(plant, lambda c: 0 if c == KEY else 8 + fixed.index(c))
    tiles = tiles + win_tiles + plant_tiles
    assert len(tiles) <= 512, len(tiles)
    win_tile, plant_tile = base_tile, base_tile + 8
    pals[WIN_PAL] = [(0, 0, 0)] + [((p & 31) << 3, ((p >> 5) & 31) << 3, ((p >> 10) & 31) << 3) for p in view_pals[0][1:]]

    # The stairwell a tile right: rebuild columns 6-8, rows 0-1, from 8px columns.
    new_mets, new_attrs = list(mets), list(attrs)
    def add_met(m, a):
        new_mets.append(m); new_attrs.append(a); return SEC + len(new_mets) - 1
    shifted = {}
    for row in (0, 1):
        old = [met(cell(x, row) & 0x3FF) for x in (6, 7, 8)]
        # per layer, per tile row (2 per metatile), the six 8px columns x 96..144
        cols = {}
        for layer in (0, 1):
            for ty in (0, 1):
                cols[layer, ty] = [old[c][layer * 4 + ty * 2 + h] for c in range(3) for h in range(2)]
        for layer in (0, 1):
            for ty in (0, 1):
                c = cols[layer, ty]
                cols[layer, ty] = [c[0], c[0], c[1], c[2], c[3], c[4]]   # door tiles 13-16 -> 14-17; 12 repeats as wall
        for i, x in enumerate((6, 7, 8)):
            m = [cols[layer, ty][i * 2 + h] for layer in (0, 1) for ty in (0, 1) for h in range(2)]
            if x == 6:   # the window, on the top layer over the wall
                m[4:8] = [entry(SEC + win_tile + row * 4 + k, WIN_PAL) for k in range(4)]
            shifted[x, row] = add_met(m, attr(cell(x, row) & 0x3FF))
    # Plants: the floor underneath stays, the plant on the top layer.
    plant_ids = {}
    for name, (px_, py_) in (('A', (0, 6)), ('B', (8, 3))):
        for half in (0, 1):
            under = cell(px_, py_ + half) & 0x3FF
            m = list(met(under))
            m[4:8] = [entry(SEC + plant_tile + half * 4 + k, WIN_PAL) for k in range(4)]
            plant_ids[name, half] = (add_met(m, attr(under)), under)
    assert len(new_mets) <= 512

    # ---- files
    to_png(tiles, DST + 'tiles.png', pals[6])
    for i in range(16): jasc_write(DST + f'palettes/{i:02}.pal', pals[i])
    open(DST + 'metatiles.bin', 'wb').write(b''.join(struct.pack('<8H', *m) for m in new_mets))
    open(DST + 'metatile_attributes.bin', 'wb').write(b''.join(struct.pack('<H', a) for a in new_attrs))
    allf = [t for f in frames for t in f]
    to_png(allf, DST + 'anim/window.png', pals[WIN_PAL], per_row=2)
    for (x, row), mid in shifted.items():
        grid[row * W + x] = (grid[row * W + x] & ~0x3FF) | mid
    open(R + L['blockdata_filepath'], 'wb').write(struct.pack(f'<{len(grid)}H', *grid))
    L['secondary_tileset'] = 'gTileset_WildcardBedroom'
    s = json.dumps(lay, indent=2) + '\n'
    open(R + 'data/layouts/layouts.json', 'w').write(s)

    # ---- C
    consts = [f'#define WINDOW_VIEW_{v.upper()} {i}' for i, v in enumerate(VIEWS)] + [f'#define WINDOW_VIEW_COUNT {len(VIEWS)}', '']
    for (name, half), (mid, under) in sorted(plant_ids.items()):
        consts.append(f'#define METATILE_BEDROOM_PLANT_{name}{half} 0x{mid:03X}')
        consts.append(f'#define METATILE_BEDROOM_FLOOR_{name}{half} 0x{under:03X}')
    consts += ['#define BEDROOM_PLANT_A_X 0', '#define BEDROOM_PLANT_A_Y 6', '#define BEDROOM_PLANT_B_X 8', '#define BEDROOM_PLANT_B_Y 3']
    open(R + 'include/constants/wildcard_bedroom.h', 'w').write(
        '#ifndef GUARD_CONSTANTS_WILDCARD_BEDROOM_H\n#define GUARD_CONSTANTS_WILDCARD_BEDROOM_H\n\n'
        '// Generated by wildcard/art/rooms/build_bedroom.py; edit there.\n// The bedroom window\'s views (RoomTheme.window) and the plants\' metatiles (RoomTheme.plants).\n'
        + '\n'.join(consts) + '\n\n#endif // GUARD_CONSTANTS_WILDCARD_BEDROOM_H\n')
    lines = ['// Daily Underdog: the bedroom window (generated by wildcard/art/rooms/build_bedroom.py; edit there).',
             '// Frames: view, then time (day, sunset, night), then 4 animation frames; 8 tiles each.',
             f'#define BEDROOM_WINDOW_TILE {win_tile}', '#define BEDROOM_WINDOW_TILES 8', f'#define BEDROOM_WINDOW_FRAMES {FRAMES}', f'#define BEDROOM_WINDOW_PAL {WIN_PAL}', '',
             'static const u16 sBedroomWindowFrames[] = INCGFX_U16("data/tilesets/secondary/wildcard_bedroom/anim/window.png", ".4bpp");', '',
             f'static const u16 sBedroomWindowPalettes[WINDOW_VIEW_COUNT][3][16] =', '{']
    for vi, v in enumerate(VIEWS):
        lines.append(f'    [WINDOW_VIEW_{v.upper()}] = {{')
        for ti in range(3):
            p = view_pals[vi * 3 + ti]
            lines.append('        { ' + ', '.join(f'0x{c:04X}' for c in p) + ' },')
        lines.append('    },')
    lines.append('};')
    open(R + 'src/data/tilesets/wildcard_bedroom_anims.h', 'w').write('\n'.join(lines) + '\n')

    write_block(R + 'src/data/tilesets/graphics.h',
        'const u32 gTilesetTiles_WildcardBedroom[] = INCGFX_U32("data/tilesets/secondary/wildcard_bedroom/tiles.png", ".4bpp.fastSmol");\n\n'
        'const u16 gTilesetPalettes_WildcardBedroom[][16] =\n{\n'
        + ''.join(f'    INCGFX_U16("data/tilesets/secondary/wildcard_bedroom/palettes/{i:02}.pal", ".gbapal"),\n' for i in range(16)) + '};')
    write_block(R + 'src/data/tilesets/metatiles.h',
        'const u16 gMetatiles_WildcardBedroom[] = INCBIN_U16("data/tilesets/secondary/wildcard_bedroom/metatiles.bin");\n'
        'const u16 gMetatileAttributes_WildcardBedroom[] = INCBIN_U16("data/tilesets/secondary/wildcard_bedroom/metatile_attributes.bin");')
    write_block(R + 'src/data/tilesets/headers.h',
        'const struct Tileset gTileset_WildcardBedroom =\n{\n    .isCompressed = TRUE,\n    .isSecondary = TRUE,\n'
        '    .tiles = gTilesetTiles_WildcardBedroom,\n    .palettes = gTilesetPalettes_WildcardBedroom,\n'
        '    .metatiles = gMetatiles_WildcardBedroom,\n    .metatileAttributes = gMetatileAttributes_WildcardBedroom,\n'
        '    .callback = InitTilesetAnim_WildcardBedroom,\n};')
    write_block(R + 'include/tileset_anims.h', 'void InitTilesetAnim_WildcardBedroom(void);')
    print('tiles', len(tiles), 'metatiles', len(new_mets), 'window frames', len(frames), 'plants', plant_ids)

if __name__ == '__main__':
    main()
