def arena_spec(name, s, top, board1, board2, music='MUS_B_DOME', dim=0.0, mode=None):
    """Grand and Neon: stands above and below, LED boards, side stands by a 3-row pitch."""
    sp = Spec(name, s, music)
    back, front = crowd_layers(s, mode=mode, dim=dim)
    sp.layers.update(back=back, front=front, board1=board_layer(s, board1), board2=board_layer(s, board2))
    aisles = (6, 18)
    sp.stand('back', 0, W, 2, 4, aisles); sp.stand('front', 0, W, 11, 4, aisles)
    sp.stand('back', 0, 3, 7, 3, yoff=T); sp.stand('back', W - 3, W, 7, 3, yoff=T)
    sp.strip('board1', 6); sp.strip('board2', 10)
    sp.walk = {(x, y) for y in range(7, 10) for x in range(3, W - 3)}
    def static(img):
        top(img)
        draw_aisles(img, s, aisles, ((2, 6), (11, 15)))
        K.pitch(img, 3, 7, W - 3, 10, s, 0)
        rect(img, 3 * T, 7 * T, 3 * T + 1, 10 * T - 1, s['board_frame']); rect(img, (W - 3) * T - 2, 7 * T, (W - 3) * T - 1, 10 * T - 1, s['board_frame'])
        rect(img, 0, 15 * T, W * T - 1, H * T - 1, shade(s['riser'], -0.3))
    sp.static = static
    return sp

