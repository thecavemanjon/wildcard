def sky_clouds(s, base, step=2):
    """Open sky with clouds drifting left: 128 x 64 px, repeated over the whole map
    under the islands. The sky colour is recoloured per band of rows (the gradient)."""
    rnd = random.Random(3); P, Hp = 128, 64
    puffs = [(10, 12, 38), (78, 42, 24)]
    frames = []
    for off in range(0, P, step):
        img = Image.new('RGB', (P, Hp), base)
        for (x, y, w) in puffs:
            for k in (-P, 0, P): K.cloud(img, x - off + k, y, w, s['cloud_near'])
        frames.append(img)
    return frames

def sky_arena(variant, name):
    """Floating islands: a grandstand island above, the pitch on its own island
    with a rocky underside. Clouds drift across the whole sky on the layer
    beneath, showing through every gap."""
    s = dict(S.SKY[variant])
    sp = Spec(name, s, 'MUS_B_TOWER')
    back, _ = crowd_layers(s, 3, 1)
    sp.layers['back'] = back
    sp.layers['clouds'] = Layer(sky_clouds(s, gba(mix(s['sky'][0], s['sky'][1], 0.4))), 6, own=True)
    for y in range(H):
        for x in range(W): sp.under[x, y] = ("clouds", (y // 4) * 53, (y % 4) * T)
    sp.stand('back', 6, 19, 2, 3)
    # one tile in from the island's edges, so the camera never shows past the map
    sp.walk = {(x, y) for y in range(7, 10) for x in range(7, 18)}
    sp.border = (0, 0)
    rock, rock_d, rock_l, grass = (150, 120, 96), (104, 80, 64), (184, 152, 120), (104, 184, 88)
    def underside(img, x0, x1, y_top, depth):
        """A floating island's underside: a grass lip, then rock tapering to a point."""
        d = ImageDraw.Draw(img); X0, X1 = x0 * T, x1 * T - 1; Y = y_top * T; cx = (X0 + X1) // 2
        d.polygon([(X0, Y), (X1, Y), (cx + 6, Y + depth), (cx - 6, Y + depth)], fill=rock)
        for k in range(1, 5):  # rock strata
            yy = Y + depth * k // 5; half = (X1 - X0) // 2 * (5 - k) // 5
            d.line([cx - half + 2, yy, cx + half - 2, yy], fill=rock_d)
        d.polygon([(cx - 6, Y + depth), (cx + 6, Y + depth), (cx, Y + depth + 6)], fill=rock_d)
        d.line([X0, Y, cx - 6, Y + depth], fill=rock_l); d.line([X1, Y, cx + 6, Y + depth], fill=rock_d)
        rect(img, X0, Y, X1, Y + 3, grass); rect(img, X0, Y + 3, X1, Y + 4, shade(grass, -0.3))
        for x in range(X0 + 5, X1 - 4, 11):  # roots and vines hanging off the lip
            d.line([x, Y + 4, x, Y + 7 + (x * 7) % 6], fill=shade(grass, -0.4))
    def static(img):
        rect(img, 0, 0, W * T - 1, H * T - 1, KEY)   # all sky: the clouds layer shows through
        underside(img, 6, 19, 5, 13)        # the grandstand's island
        K.pitch(img, 6, 7, 19, 10, s, 0)
        underside(img, 6, 19, 10, 50)       # the pitch's island
        railings(img, 6, 19, 7, 10)
        d = ImageDraw.Draw(img)
        for fx in (6, 18): d.rectangle([fx * T + 2, 6 * T, fx * T + 3, 7 * T + 6], fill=(200, 200, 208))
    def railings(img, x0, x1, y0, y1):
        """White railings round the pitch: along the back, the front lip, and down both ends."""
        rail, post, dark = (236, 236, 244), (168, 168, 184), (112, 112, 128)
        X0, X1, Y0, Y1 = x0 * T, x1 * T - 1, y0 * T, y1 * T
        for ry in (Y0 - 7, Y1 - 2):                      # back and front: posts and a top bar
            for x in range(X0, X1 + 1, 8): rect(img, x, ry + 2, x + 1, ry + 7, post)
            rect(img, X0, ry, X1, ry + 1, rail); rect(img, X0, ry + 2, X1, ry + 2, dark)
        for rx in (X0, X1 - 3):                          # the two ends, seen from above
            rect(img, rx, Y0 - 7, rx + 3, Y1 + 5, rail); rect(img, rx + 3 if rx == X0 else rx, Y0 - 7, rx + 3 if rx == X0 else rx, Y1 + 5, dark)
            for y in range(Y0 - 4, Y1 + 5, 8): rect(img, rx, y, rx + 3, y + 1, post)
    sp.static = static
    ff = []
    for f in range(4):
        img = Image.new('RGB', (W * T, H * T)); static(img)
