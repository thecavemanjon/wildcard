# ---- tiles and palettes ---------------------------------------------------------------------
def tile_at(img, tx, ty):
    px = img.load()
    return tuple(px[tx * 8 + i % 8, ty * 8 + i // 8] for i in range(64))

def quantised_palette(images, n=15):
    strip = Image.new('RGB', (max(i.width for i in images), sum(i.height for i in images)))
    y = 0
    for i in images: strip.paste(i, (0, y)); y += i.height
    cols = set(strip.getdata())
    if len(cols) <= n: return sorted(cols)
    q = strip.quantize(n, method=Image.Quantize.MEDIANCUT)
    p = q.getpalette()[:n * 3]
    return sorted({gba(tuple(p[i * 3:i * 3 + 3])) for i in range(n)})

def nearest(pal, c):
    return min(range(len(pal)), key=lambda i: sum((pal[i][k] - c[k]) ** 2 for k in range(3)))

def remap(img, pal):
    cache = {}; px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            c = px[x, y]
            if c not in cache: cache[c] = pal[nearest(pal, c)]
            px[x, y] = cache[c]

def pack_palettes(colour_sets, limit):
    pals = []
    for cs in sorted(set(colour_sets), key=len, reverse=True):
        for p in pals:
            if len(p | cs) <= 15: p |= cs; break
        else:
            pals.append(set(cs))
            if len(pals) > limit: return None
    return [sorted(p) for p in pals]

def frames_png(path, frames, n_tiles, pal_preview):
    rows = n_tiles // 16
    img = Image.new('P', (128, rows * 8 * len(frames)))
    img.putpalette([v for c in ([(0, 0, 0)] + list(pal_preview) + [(0, 0, 0)] * 16)[:16] for v in c] + [0] * 240 * 3)
    px = img.load()
    for f, tiles in enumerate(frames):
        for k, t in enumerate(tiles):
            X, Y = (k % 16) * 8, (f * rows + k // 16) * 8
            for i, v in enumerate(t): px[X + i % 8, Y + i // 8] = v
    img.save(path)

pad16 = lambda n: (n + 15) // 16 * 16

KEY = (248, 0, 248)  # "see-through" in a static image: the layer underneath shows

def build(spec):
    s, name = spec.s, spec.name; low = name.lower()
    tdir = R + f'data/tilesets/secondary/wildcard_{low}/'
    os.makedirs(tdir + 'palettes', exist_ok=True); os.makedirs(tdir + 'anim', exist_ok=True)
    for f in os.listdir(tdir + 'anim'): os.remove(tdir + 'anim/' + f)
    static = Image.new('RGB', (W * T, H * T), (0, 0, 0)); spec.static(static); gba_image(static)

    # layers with a palette of their own: the crowd (one shared palette) and any
    # layer marked own (its palette, plus a recoloured copy per colour band)
    crowd_names = [n for n, l in spec.layers.items() if l.crowd]
    own_names = [n for n, l in spec.layers.items() if l.own]
    crowd_pal = quantised_palette([f for n in crowd_names for f in spec.layers[n].frames]) if crowd_names else []
    for n in crowd_names:
        for f in spec.layers[n].frames: remap(f, crowd_pal)
    own_pals = {}
    for n in own_names:
        l = spec.layers[n]; pal = quantised_palette(l.frames)
        for f in l.frames: remap(f, pal)
        variants = [pal]
        if l.bands:
            base, bands = l.bands
            for (_, _, col) in bands: variants.append([gba(col) if c == gba(base) else c for c in pal])
        own_pals[n] = variants
    reserved = (1 if crowd_names else 0) + sum(len(v) for v in own_pals.values())
    budget = 7 - reserved
    is_own = lambda l: l.crowd or l.own
    def covered(x, y): return (x, y) in spec.cells or any((x, y) in r.cells for r in spec.regions.values())

    # every other tile, static or moving: a colour set per tile (moving ones: across all frames)
    def other_sets():
        sets = []
        for y in range(H):
            for x in range(W):
                if covered(x, y): continue
                for sub in range(4): sets.append(frozenset(c for c in tile_at(static, x * 2 + sub % 2, y * 2 + sub // 2) if c != KEY))
        for n, l in spec.layers.items():
            if is_own(l): continue
            for ty in range(l.h // 8):
                for tx in range(l.P // 8):
                    sets.append(frozenset(c for f in l.frames for c in tile_at(f, tx, ty)))
        for r in spec.regions.values():
            for (x, y) in r.cells:
                for sub in range(4):
                    sets.append(frozenset(c for f in r.frames for c in tile_at(f, x * 2 + sub % 2, y * 2 + sub // 2) if c != KEY))
        return [st for st in sets if st]
    pals = pack_palettes(other_sets(), budget)
    n_cols = 64
    while pals is None:  # too colourful: squeeze every shared-palette image into fewer colours and retry
        imgs = [static] + [f for l in spec.layers.values() if not is_own(l) for f in l.frames] + [f for r in spec.regions.values() for f in r.frames]
        shared = quantised_palette(imgs, n_cols)
        keep = lambda im: [(x, y) for y in range(im.height) for x in range(im.width) if im.getpixel((x, y)) == KEY]
        for im in imgs:
            holes = keep(im); remap(im, shared)
            for xy in holes: im.putpixel(xy, KEY)
        pals = pack_palettes(other_sets(), budget)
        n_cols -= 8
        assert n_cols > 8, f'{name}: cannot fit the palettes'
    pals = pals or [[]]
    n_shared = len(pals)
    if crowd_names: CROWD_P = len(pals); pals = pals + [crowd_pal]
    own_p = {}
    for n in own_names: own_p[n] = len(pals); pals = pals + own_pals[n]

    def pal_for(colours):
        colours = {c for c in colours if c != KEY}
        return next(i for i, p in enumerate(pals[:n_shared]) if colours <= set(p))
    def index(t, p): return tuple(0 if c == KEY else pals[p].index(c) + 1 for c in t)

    tiles = [tuple([0] * 64)]; tile_id = {}
    def static_tile(t):
        if all(c == KEY for c in t): return 0, 0
        p = pal_for(set(t)); it = index(t, p)
        if (it, p) not in tile_id: tile_id[it, p] = len(tiles); tiles.append(it)
        return tile_id[it, p], p
    def reserve(n):
        base = len(tiles); tiles.extend([tuple([0] * 64)] * n); return base

    anims = []   # (array name, first tile, tiles per frame, frames as tile lists, interval)
    layer_info = {}
    for n, l in spec.layers.items():
        tw, th = l.P // 8, l.h // 8; ntile = pad16(tw * th); base = reserve(ntile)
        tpal = []
        for ty in range(th):
            for tx in range(tw):
                tpal.append(CROWD_P if l.crowd else own_p[n] if l.own else pal_for({c for f in l.frames for c in tile_at(f, tx, ty)}))
        frames = []
        for f in l.frames:
            ts = [index(tile_at(f, k % tw, k // tw), tpal[k]) for k in range(tw * th)]
            frames.append(ts + [tuple([0] * 64)] * (ntile - tw * th))
        for k, t in enumerate(frames[0]): tiles[base + k] = t
        layer_info[n] = (base, tw, tpal)
        anims.append((n, base, ntile, frames, l.interval))
    region_info = {}
    for n, r in spec.regions.items():
        ntile = pad16(len(r.cells) * 4); base = reserve(ntile)
        tpal = []
        for (x, y) in r.cells:
            for sub in range(4):
                tpal.append(pal_for({c for f in r.frames for c in tile_at(f, x * 2 + sub % 2, y * 2 + sub // 2)}) if any(c != KEY for f in r.frames for c in tile_at(f, x * 2 + sub % 2, y * 2 + sub // 2)) else 0)
        frames = []
        for f in r.frames:
            ts = [index(tile_at(f, x * 2 + sub % 2, y * 2 + sub // 2), tpal[i * 4 + sub]) for i, (x, y) in enumerate(r.cells) for sub in range(4)]
            frames.append(ts + [tuple([0] * 64)] * (ntile - len(ts)))
        for k, t in enumerate(frames[0]): tiles[base + k] = t
        region_info[n] = (base, tpal, {c: i for i, c in enumerate(r.cells)})
        anims.append((n, base, ntile, frames, r.interval))

    def layer_entries(x, y, n, ox, oy):
        base, tw, tpal = layer_info[n]; l = spec.layers[n]; out = []
        band = 0
        if l.own and l.bands:
            for i, (y0, y1, _) in enumerate(l.bands[1]):
                if y0 <= y <= y1: band = i + 1
        for sub in range(4):
            col = ((x * T + (sub % 2) * 8 + ox) // 8) % tw; row = ((oy + (sub // 2) * 8) // 8) % (l.h // 8)
            out.append(entry(base + row * tw + col, tpal[row * tw + col] + band))
        return out

    # metatiles: the main graphics, and under them (if the cell has one) a layer that shows through
    def entry(local, pal): return (512 + local) | (6 + pal) << 12
    blank = entry(0, 0)
    metas, attrs, meta_id, grid = [], [], {}, [[0] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            region = next(((n, ri) for n, ri in region_info.items() if (x, y) in ri[2]), None)
            if region:
                base, tpal, idx = region[1]
                ents = [entry(base + idx[x, y] * 4 + sub, tpal[idx[x, y] * 4 + sub]) for sub in range(4)]
            elif (x, y) in spec.cells:
                ents = layer_entries(x, y, *spec.cells[x, y])
            else:
                ents = []
                for sub in range(4):
                    i, p = static_tile(tile_at(static, x * 2 + sub % 2, y * 2 + sub // 2)); ents.append(entry(i, p))
            if (x, y) in spec.under:
                m, attr = tuple(layer_entries(x, y, *spec.under[x, y]) + ents), 1 << 12  # METATILE_LAYER_TYPE_COVERED
            else:
                m, attr = tuple(ents + [blank] * 4), 0                                  # METATILE_LAYER_TYPE_NORMAL
            if (m, attr) not in meta_id: meta_id[m, attr] = len(metas); metas.append(m); attrs.append(attr)
            grid[y][x] = meta_id[m, attr]
    assert len(tiles) <= 512, f'{name}: {len(tiles)} tiles, the secondary set holds 512'
    assert len(metas) <= 512, f'{name}: {len(metas)} metatiles'
    assert len(pals) <= 7, f'{name}: {len(pals)} palettes'

    # files
    img = Image.new('P', (128, (len(tiles) + 15) // 16 * 8))
    img.putpalette([v for c in ([(0, 0, 0)] + pals[0] + [(0, 0, 0)] * 16)[:16] for v in c] + [0] * 240 * 3)
    px = img.load()
    for k, t in enumerate(tiles):
        for i, v in enumerate(t): px[(k % 16) * 8 + i % 8, (k // 16) * 8 + i // 8] = v
    img.save(tdir + 'tiles.png')
    src = R + 'data/tilesets/secondary/battle_dome/palettes/'
    for i in range(16):
        if 6 <= i <= 12:
            p = pals[i - 6] if i - 6 < len(pals) else []
            BA.write_jasc(tdir + f'palettes/{i:02}.pal', ([(0, 0, 0)] + list(p) + [(0, 0, 0)] * 16)[:16])
        else:
            open(tdir + f'palettes/{i:02}.pal', 'w').write(open(src + f'{i:02}.pal').read())
    open(tdir + 'metatiles.bin', 'wb').write(b''.join(struct.pack('<8H', *m) for m in metas))
    open(tdir + 'metatile_attributes.bin', 'wb').write(b''.join(struct.pack('<H', a) for a in attrs))
    out = []
    for i, (n, base, ntile, frames, interval) in enumerate(anims):
        frames_png(tdir + f'anim/{n}.png', frames, ntile, pals[0])
        out.append((n, base, ntile, len(frames), interval, i % interval))
    period = 1
    for a in out: period = period * (a[3] * a[4]) // math.gcd(period, a[3] * a[4])
    assert period < 65536, f'{name}: animation period {period} is too long for the counter'

    # the map: the walkable floor, everything else solid
    blocks = [[grid[y][x] + 512 | (0 if (x, y) in spec.walk else 1) << 10 | 3 << 12 for x in range(W)] for y in range(H)]
    mapname = f'UnderdogArena_{name}'
    bx, by = spec.border
    BA.write_layout(mapname, blocks, [grid[by][bx] + 512 | 1 << 10] * 4)
    lid = BA.add_layout(mapname, W, H, f'gTileset_Wildcard{name}', 'gTileset_Building')
    mid = BA.write_map(mapname, lid, spec.music, spec.weather,
                       [BA.obj('OBJ_EVENT_GFX_VAR_0', OX, ROW, move='MOVEMENT_TYPE_FACE_LEFT')] + mascot_objs(name), spec.map_type,
                       note=f'the {name} stadium (the opponent waits on the right; you start on the left).', face='DIR_EAST')
    if MASCOTS.get(name, (0, 0, 0, 0))[3]: add_float_script(mapname)
    copies = []
    for cname, objs, slots in COPIES.get(name, []):
        cmap = f'UnderdogArena_{name}{cname}'
        cid = BA.write_map(cmap, lid, spec.music, spec.weather,
                           [BA.obj('OBJ_EVENT_GFX_VAR_0', OX, ROW, move='MOVEMENT_TYPE_FACE_LEFT')] +
                           [BA.obj(g, x, y, move='MOVEMENT_TYPE_FACE_LEFT') for g, x, y in objs] + mascot_objs(name), spec.map_type,
                           note=f'the {name} stadium, with room for {cname}.', face='DIR_EAST')
        if MASCOTS.get(name, (0, 0, 0, 0))[3]: add_float_script(cmap)
        copies.append((cmap, cid, slots))
    print(f'{name:13} {len(tiles):3} tiles, {len(metas):3} metatiles, {len(pals)} palettes, period {period:5}; {mid}')
    return dict(name=name, low=low, anims=out, period=period, mapname=mapname, mapid=mid, copies=copies)

