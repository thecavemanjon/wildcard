# Builds the stadiums into the game's data: per stadium a secondary tileset
# (tiles, palettes, metatiles), its animation frames, the C tables that play
# them, and the arena map. Rerunnable: it rewrites its own files and the marked
# blocks it owns.
#
#   cd wildcard/art/stadiums && python3 build_stadium.py
#
# How the movement works (DECISIONS 2026-10-19). Two kinds of moving part:
#   patterns  a strip P pixels wide repeated along the map (a crowd stand, an
#             LED board's text, lava, water), so every copy shares one set of
#             tiles and redrawing those tiles moves all of them at once;
#   regions   a few fixed cells (torches, flags, deck lights) with their own tiles.
# Everything else is ordinary deduplicated static tiles. The C side is the
# generic player at the end of src/tileset_anims.c.
