def splice(path, block, before='#else'):
    s = open(path).read()
    if MARK_BEGIN in s:
        a = s.index(MARK_BEGIN); b = s.index(MARK_END) + len(MARK_END) + 1
        s = s[:a] + block + s[b:]
    else:
        i = s.index('\n' + before + '\n') + 1
        s = s[:i] + block + '\n' + s[i:]
    open(path, 'w').write(s)

