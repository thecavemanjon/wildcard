    for b in built:
        for slot, mapid in [(sl, b['mapid']) for sl in HOMES.get(b['name'], [])] + [(sl, c[1]) for c in b['copies'] for sl in c[2]]:
            c, n = re.subn(rf'(    \[\s*{slot}\] = {{ )MAP_\w+,\s*\d+,\s*\d+( }}, // )([^:,\n]+)[^\n]*',
                           rf'\g<1>{mapid + ",":32} {PX:2}, {ROW:2}\g<2>\g<3>: {b["name"]} stadium', c)
            assert n == 1, f'slot {slot} not found in sArenaRooms'
